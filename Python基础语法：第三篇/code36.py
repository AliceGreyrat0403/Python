# Python中的关键字：global
# x = 10
#
# def test():
#     # 声明，变成针对全局变量来进行的了
#     global x
#     x = 20  # 这个x被当成函数内部的局部变量了
#     # 由于修改全局变量的操作和创建变量的语法是一模一样的，所以Python把它当做是局部变量了
#     # （所以要加上 global 进行显式声明）
#
# test()
# print(f"x = {x}")
# 没有 global ，此时就会把x = 20当做是在函数内部创建了一个局部变量 x
# 而实际上是要修改全局变量 x ，为了让函数里面知道 x 是个全局变量，就使用 global 关键字先声明一下
