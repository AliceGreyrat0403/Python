# 在函数中尝试访问某个变量的时候，会先尝试在局部变量中查找，如果找到，就直接访问；
# 如果没找到，就会往上一级作用域中进行查找-->test再往上一级作用域，就是全局了

# 使用这个函数，把全局变量 x 给改成 20！

