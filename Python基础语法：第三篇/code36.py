#     return x,y

# 函数内部的变量名，只能在函数内部生效，出了函数，就无效了！
# x,y = getPoint()
# print(x,y)
# 变量的作用域！
# 一个变量名的生效范围是一定的！只在一个固定的区域内生效

# def getPoint():
#     x = 10
#     y = 20
#     return x,y
#
# getPoint()
# print(x,y)
# 函数内部的x，y不生效-->NameError: name 'x' is not defined
# 函数内部和函数外部是可以使用同名的变量的，虽然变量名相同，但是是不同的变量！

