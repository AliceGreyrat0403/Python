# 缩进和代码块

a = input("请输入一个整数：")
if a == '1':
    # 带有缩进的情况-->如果条件成立，那么aaaa和bbbb都会打印
    # 如果条件不成立，那么都不会打印！
    print('aaaa')
    print('bbbb')
# 没有缩进的情况-->无论条件是否有关，都要执行
# cccc是和条件无关了，条件是否成立都会打印cccc，已经是不属于条件语句中的内容了！
print('cccc')
