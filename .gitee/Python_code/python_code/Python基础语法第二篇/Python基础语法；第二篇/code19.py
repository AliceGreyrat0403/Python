# 在Pyhton中，缩进表示代码块
# 在if，else，elif，while，for……需要跟上代码块的部分，都是需要使用缩进来表示的
# 在C++/Java中，对于代码缩进是没有强制要求的，缩进具体怎么写都不影响代码的编译运行结果
# 如果缩进没有好好的统一风格来写，也是对于可读性比较影响
# 在其他语言中，缩进作为一个软性要求（一般也要求把代码写得缩进尽量统一一点）
# 在Pyhton中，缩进作为一个硬性要求

